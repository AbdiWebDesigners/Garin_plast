<?php

require_once __DIR__ . '/../includes/auth.php';
require_once __DIR__ . '/../includes/db.php';

requireLogin();

global $pdo;

/*
|--------------------------------------------------------------------------
| دریافت شناسه کاربر
|--------------------------------------------------------------------------
*/

$id = (int)($_GET['id'] ?? 0);

if ($id <= 0) {

    header("Location: index.php");
    exit;
}

/*
|--------------------------------------------------------------------------
| دریافت اطلاعات کاربر
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
SELECT
    id,
    fullname,
    mobile,
    email,
    role,
    job_title,
    department,
    national_code,
    address,
    description,
    avatar,
    status,
    last_login,
    last_ip,
    created_at,
    updated_at
FROM users
WHERE id = ?
LIMIT 1
");

$stmt->execute([$id]);

$user = $stmt->fetch(PDO::FETCH_ASSOC);

/*
|--------------------------------------------------------------------------
| اگر کاربر وجود نداشت
|--------------------------------------------------------------------------
*/

if (!$user) {

    $_SESSION['error'] = 'کاربر مورد نظر یافت نشد.';

    header("Location: index.php");

    exit;
}

/*
